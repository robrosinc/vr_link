"""Flat "Unreal" calibration YAML (``left_fx: ...``) and ready JSON files.

The flat format is what the checkerboard tool writes and what the hardware
calibration server has always served: scalar keys only, so the C++ side can
parse key/value pairs without OpenCV matrix tags. Metadata keys precede the
per-eye blocks; ``{side}_{fx..k4,r00..r22}`` carry the numbers.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, Iterable, Mapping, Optional, Sequence, Union

from .ideal import flatten_sides
from .schema import CAMERA_FIELDS, R_KEYS, SIDES, CalibrationError, validate_calibration

PathLike = Union[str, Path]

# Header comment written above generated ideal-calibration files.
IDEAL_YAML_COMMENT = (
    "# Ideal stereo calibration of simulated pinhole eye cameras.",
    "# Generated by vr-link-make-calibration; do not hand-edit, re-run the generator",
    "# when the render size, fovy or toe-out angle changes.",
    "# Same flattened key set as the measured hardware YAML so the calibration",
    "# server (port 9101) serves it unchanged.",
    "# k1..k4 are the tan(theta) series coefficients: the receiver's fisheye shader then",
    "# reproduces the simulator's pinhole projection exactly (k=0 would mean equidistant).",
)

MEASURED_YAML_COMMENT = (
    "# Unreal material-friendly stereo fisheye calibration.",
    "# Values are flattened so C++ can parse key/value pairs without OpenCV matrix tags.",
)


def _yaml():
    try:
        import yaml  # noqa: WPS433 (lazy: the base package must import without pyyaml)
    except ImportError as error:  # pragma: no cover - environment dependent
        raise ImportError("pyyaml is required to read calibration YAML: install the 'yaml' extra") from error
    return yaml


def load_unreal_yaml(path: PathLike, *, image_width: Optional[int] = None, image_height: Optional[int] = None) -> Dict[str, Any]:
    """Read a flat calibration YAML into the JSON-schema dict (validated).

    ``image_width``/``image_height`` override the file's values (the legacy
    stream config allowed that); ``0``/``None`` keep the file's values.
    """

    with open(path, encoding="utf-8") as handle:
        data = _yaml().safe_load(handle)
    if not isinstance(data, Mapping):
        raise CalibrationError(f"{path}: top level must be a mapping")

    def camera(side: str) -> Dict[str, Any]:
        try:
            cam: Dict[str, Any] = {field: float(data[f"{side}_{field}"]) for field in CAMERA_FIELDS}
            cam["r"] = [float(data[f"{side}_{key}"]) for key in R_KEYS]
        except KeyError as error:
            raise CalibrationError(f"{path}: missing key {error.args[0]!r}") from error
        return cam

    cal: Dict[str, Any] = {
        "image_width": int(image_width or data.get("image_width", 0)),
        "image_height": int(image_height or data.get("image_height", 0)),
        "left": camera("left"),
        "right": camera("right"),
    }
    for key in ("camera_model", "left_half", "fovy_deg", "toe_out_deg"):
        if key in data:
            cal[key] = data[key]
    if "baseline" in data:
        cal["baseline_mm"] = float(data["baseline"])
    return validate_calibration(cal)


def _scalar(value: Any, float_digits: Optional[int]) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        if float_digits is None:
            return f"{value:.17g}"  # exact round trip of measured values
        # Round away float noise (e.g. 240.00000000000003) without losing meaningful digits.
        return repr(round(value, float_digits))
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def dump_unreal_yaml(
    cal: Mapping[str, Any],
    *,
    meta: Optional[Mapping[str, Any]] = None,
    comments: Sequence[str] = IDEAL_YAML_COMMENT,
    float_digits: Optional[int] = 12,
) -> str:
    """Render the flat YAML text: comments, ``meta`` scalars in order, then per-eye blocks.

    ``meta`` defaults to the size and model keys present in ``cal``; pass the
    full ordered mapping to reproduce a specific file layout. ``float_digits``
    rounds generated values (``None`` writes 17 significant digits, for
    measured calibrations).
    """

    valid = validate_calibration(cal)
    lines = list(comments)
    if meta is None:
        meta = {
            "camera_model": valid.get("camera_model", "pinhole_as_fisheye_tan_series"),
            "left_half": valid.get("left_half", "right"),
            "image_width": valid["image_width"],
            "image_height": valid["image_height"],
        }
        for key in ("fovy_deg", "toe_out_deg"):
            if key in valid:
                meta[key] = valid[key]
        if "baseline_mm" in valid:
            meta["baseline"] = valid["baseline_mm"]
            meta["baseline_unit"] = "mm"
    for key, value in meta.items():
        lines.append(f"{key}: {_scalar(value, float_digits)}")
    lines.append("")
    flat = flatten_sides(valid)
    for side in SIDES:
        for key, value in flat.items():
            if key.startswith(f"{side}_"):
                lines.append(f"{key}: {_scalar(value, float_digits)}")
        lines.append("")
    return "\n".join(lines)


def write_unreal_yaml(path: PathLike, cal: Mapping[str, Any], **kwargs: Any) -> Path:
    """Write :func:`dump_unreal_yaml` output to ``path`` and return it."""

    target = Path(path)
    target.write_text(dump_unreal_yaml(cal, **kwargs), encoding="utf-8")
    return target


def calibration_from_json(path: PathLike, image_width: Optional[int] = None, image_height: Optional[int] = None) -> Dict[str, Any]:
    """Load a ready JSON calibration file, validating the required fields."""

    with open(path, encoding="utf-8") as handle:
        raw = json.load(handle)
    if not isinstance(raw, Mapping):
        raise CalibrationError(f"{path}: top level must be an object")
    cal = dict(raw)
    if image_width:
        cal["image_width"] = int(image_width)
    if image_height:
        cal["image_height"] = int(image_height)
    return validate_calibration(cal)


def iter_meta_keys(data: Mapping[str, Any]) -> Iterable[str]:
    """Keys of a flat YAML mapping that are not per-eye numbers."""

    for key in data:
        if not any(key.startswith(f"{side}_") for side in SIDES):
            yield key


